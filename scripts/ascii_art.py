ROWS = 7


def cell_grid(text: str, hscale: int = 2, gap: int = 1) -> list[list[int]]:
    """Bit-map the text so each glyph pixel becomes hscale wide."""
    text = text.upper()
    cols = sum(len(GLYPHS.get(ch, GLYPHS[" "])[0]) * hscale + gap for ch in text) - gap
    grid = [[0] * cols for _ in range(ROWS)]
    x = 0
    for ch in text:
        g = GLYPHS.get(ch, GLYPHS[" "])
        for ry, line in enumerate(g):
            for rx, c in enumerate(line):
                if c == "#":
                    for k in range(hscale):
                        if x + rx * hscale + k < cols:
                            grid[ry][x + rx * hscale + k] = 1
        x += len(g[0]) * hscale + gap
    return grid


def blocks(grid: list[list[int]], body: str = "█", shadow: str = "░", shadow_on: bool = True) -> list[str]:
    rows = len(grid)
    cols = len(grid[0]) if rows else 0
    solid = {(x, y) for y in range(rows) for x in range(cols) if grid[y][x]}
    shad = set()
    if shadow_on:
        shad = {(x + 1, y + 1) for (x, y) in solid if (x + 1, y + 1) not in solid}
    out = []
    for y in range(rows + (1 if shadow_on else 0)):
        line = []
        for x in range(cols + (1 if shadow_on else 0)):
            if (x, y) in solid:
                line.append(body)
            elif (x, y) in shad:
                line.append(shadow)
            else:
                line.append(" ")
        out.append("".join(line).rstrip())
    return out


def ascii_banner(text: str, hscale: int = 2, shadow_on: bool = True) -> list[str]:
    return blocks(cell_grid(text, hscale=hscale), shadow_on=shadow_on)
